"""
Benchmark: how close are AI-drafted DAGs to expert reference DAGs?

For each case in benchmarks/cases/, the drafter receives only the research
question and the names of the exposure and outcome (never the reference
graph). Its draft is compared with the reference both structurally (skeleton
and oriented-edge F1, structural Hamming distance) and inferentially
(adjustment identification distance, and whether the draft leads to a valid
analysis of the target effect). Results go to docs/BENCHMARK.md.

Run:
    python scripts/benchmark_extraction.py               # model from AI settings / .env
    python scripts/benchmark_extraction.py --repeats 5   # repeat to average over sampling
    python scripts/benchmark_extraction.py --baseline    # no model: exposure -> outcome only

Add a case by dropping a JSON file in benchmarks/cases/ with "question",
"exposure", "outcome" and a "reference" graph ({"nodes": [...], "edges": [...]}),
or "seed_project" to use one of the built-in studies. Cite where the reference
comes from in "source".
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend import agents, dag_eval  # noqa: E402
from backend.config import get_runtime_settings  # noqa: E402
from backend.schemas import CausalNode, ProjectState, ResearchQuestion  # noqa: E402
from backend.seed_data import get_seed_projects  # noqa: E402


def load_cases():
    seeds = {p.id: p for p in get_seed_projects()}
    cases = []
    for path in sorted((ROOT / "benchmarks" / "cases").glob("*.json")):
        c = json.loads(path.read_text(encoding="utf-8"))
        if c.get("seed_project"):
            p = seeds[c["seed_project"]]
            x = next(n for n in p.nodes if n.role == "exposure")
            y = next(n for n in p.nodes if n.role == "outcome")
            c.update(
                title=p.title, discipline=p.discipline, question=p.research_question,
                exposure=x.label, outcome=y.label,
                reference={
                    "nodes": [{"id": n.id, "label": n.label, "role": n.role, "observed": n.observed} for n in p.nodes],
                    "edges": [{"source": e.source, "target": e.target, "edge_type": e.edge_type} for e in p.edges if e.approved_by_researcher],
                },
            )
        cases.append(c)
    return cases


def blind_project(case) -> ProjectState:
    """What the drafter is allowed to see: the question, not the answer."""
    return ProjectState(
        title=case["title"],
        discipline=case.get("discipline", ""),
        research_question=case["question"],
        question=ResearchQuestion(exposure=case["exposure"], outcome=case["outcome"]),
        nodes=[
            CausalNode(id=agents._slug(case["exposure"]), label=case["exposure"], role="exposure", time_index=1),
            CausalNode(id=agents._slug(case["outcome"]), label=case["outcome"], role="outcome", time_index=3),
        ],
    )


async def draft(case, baseline: bool):
    proj = blind_project(case)
    if baseline:
        raw = agents._baseline_draft(proj)
        res = agents.sanitize_draft(raw, set())
        res["used_llm"] = False
        return res
    return await agents.draft_dag(proj, mode="question")


def fmt(x, d=2):
    return "–" if x is None else (f"{x:.{d}f}" if isinstance(x, float) else str(x))


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repeats", type=int, default=1)
    ap.add_argument("--baseline", action="store_true")
    args = ap.parse_args()
    t0 = time.time()
    cases = load_cases()
    rows, all_results, used_llm_any = [], [], False
    for c in cases:
        results = []
        for _ in range(args.repeats):
            d = await draft(c, args.baseline)
            used_llm_any |= d["used_llm"]
            cand = {
                "nodes": [{"id": n.id, "label": n.label, "role": n.role, "observed": n.observed} for n in d["nodes"]],
                "edges": [{"source": e.source, "target": e.target, "edge_type": e.edge_type} for e in d["edges"]],
            }
            r = dag_eval.compare(cand, c["reference"])
            r["used_llm"] = d["used_llm"]
            results.append(r)
        all_results += results
        s = dag_eval.summarise(results)
        rows.append((c, s, results[0]))

    total = dag_eval.summarise(all_results)
    st = get_runtime_settings()
    model = "none (baseline: exposure → outcome only)" if not used_llm_any else f"{st.get('active_provider')} / {st.get('active_model')}"
    lines = [
        "# Benchmark: AI-drafted DAGs against reference DAGs",
        "",
        f"Generated by `scripts/benchmark_extraction.py` on {datetime.now(timezone.utc):%Y-%m-%d}. Drafting model: **{model}**. Repeats per case: {args.repeats}. Runtime {time.time() - t0:.0f} s.",
        "",
        "The drafter sees only the research question and the names of the exposure and outcome. Each draft is compared with the reference graph structurally and by the analysis it would lead to. See `backend/dag_eval.py` for definitions.",
        "",
    ]
    if not used_llm_any:
        lines += [
            "> **This run used no language model.** The numbers are the floor that any model should beat: a draft containing only the exposure → outcome arrow. Configure a provider in the app (or `.env`) and re-run to benchmark it.",
            "",
        ]
    lines += [
        "## Summary",
        "",
        "| Metric | Mean | Better when |",
        "| :-- | --: | :-- |",
        f"| Skeleton F1 (adjacencies) | {fmt(total['skeleton_f1'])} | higher |",
        f"| Oriented-edge F1 | {fmt(total['oriented_f1'])} | higher |",
        f"| Structural Hamming distance | {fmt(total['shd'], 1)} | lower |",
        f"| Adjustment identification distance, parent | {fmt(total['aid_parent'])} | lower |",
        f"| Adjustment identification distance, ancestor | {fmt(total['aid_ancestor'])} | lower |",
        f"| Target analysis correct (share of drafts) | {fmt(total['target_analysis_correct'])} | higher |",
        "",
        "## Per case",
        "",
        "| Case | Reference | Variables matched | Skeleton F1 | Oriented F1 | SHD | AID (ancestor) | Target analysis |",
        "| :-- | :-- | --: | --: | --: | --: | --: | :-- |",
    ]
    for c, s, first in rows:
        tgt = first.get("target", {})
        verdict = "correct" if tgt.get("analysis_correct") else ("wrong" if tgt else "–")
        lines.append(
            f"| {c['title']} | {len(c['reference']['nodes'])} variables, {len(c['reference']['edges'])} arrows "
            f"| {first['nodes']['matched']}/{len(c['reference']['nodes'])} | {fmt(s['skeleton_f1'])} | {fmt(s['oriented_f1'])} "
            f"| {fmt(s['shd'], 1)} | {fmt(s['aid_ancestor'])} | {verdict} (first run) |"
        )
    lines += [
        "",
        "## Reference graphs",
        "",
        *[f"- **{c['title']}**: {c.get('source', 'source not stated')}" for c, _, _ in rows],
        "",
        "## Reading the metrics",
        "",
        "- **Skeleton and oriented F1** measure whether the same arrows are present, with and without direction.",
        "- **Structural Hamming distance** counts the arrows to add, delete or reverse to turn the draft into the reference.",
        "- **Adjustment identification distance** (Henckel, Würtzen & Weichwald 2024) is the share of ordered variable pairs for which the identification strategy read off the draft (no effect, an adjustment set, or not identifiable) would be wrong in the reference. Two graphs can differ in many arrows yet support the same analyses, or differ in one and bias an estimate; this metric measures the consequences.",
        "- **Target analysis correct** asks whether a researcher who adjusted for the draft's recommended set for the study's own exposure and outcome would obtain a valid estimate in the reference graph.",
        "",
        "This is a small starter set. Its value grows with the number of independent expert graphs; contributions of published reference DAGs are welcome (see the docstring of this script).",
    ]
    out = ROOT / "docs" / "BENCHMARK.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    asyncio.run(main())
